-- 成员头像。存的是 src/shared/avatars.ts 里那份白名单的 id（如 'fox'），
-- 不是 emoji，也不是图片。理由见那个文件的注释。
--
-- NULL = 没设过，前端用名字首字母兜底。所以这一列**不需要 DEFAULT**，
-- 老数据自动是 NULL，也就自动走首字母——不需要任何数据回填。
--
-- ⚠️ 这是 ADD COLUMN，不是重建表，所以：
--    - 不碰 members.id（README 里那条「任何迁移都不得改变 members.id」的安全）
--    - 历史账目、分摊、结算的引用一个都不动
--    - 已退租的成员也一起有了这一列，虽然他们的头像没人会看
--
-- ⚠️ 头像挂在 **members**（账号 × 房间）上，不是 accounts。和 name 保持一致：
--    你在 A 房叫「小明」、B 房叫「明哥」，头像同样是每个房间各挑一个。
--    这也顺带保住了那条隐私性质——两个社交圈之间没有共享的标识串。
--
-- 不写事务控制语句：D1 会把整个迁移文件包在一个事务里，写 BEGIN 会报错。

ALTER TABLE members ADD COLUMN avatar TEXT;
